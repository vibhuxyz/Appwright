export const GENERATED_BANNER =
  "/* GENERATED by @repo/ui-system — do not edit here.\n" +
  " * Source: libs/ts/ui-system/components/\n" +
  " * Regenerate: bun --filter @repo/ui-system emit */\n";

export function renderComponent(
  file: string,
  source: string,
  needsUseClient: boolean,
): string {
  const body = `${GENERATED_BANNER}${source}`;
  // The directive must be the very first thing in the file — before the
  // banner comment is fine, before the imports is mandatory.
  return needsUseClient ? `"use client";\n\n${body}` : body;
}
