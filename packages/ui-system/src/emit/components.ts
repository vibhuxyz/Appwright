// Which primitives hold client-side state. Under Next's App Router every
// component is a Server Component until it says otherwise, and a Radix
// primitive that uses context or hooks crashes the page with a 500 at
// runtime — not a type error, so `tsc` will never catch it.
//
// The list is per-file rather than "mark them all", because `"use client"`
// on a leaf that does not need it drags the whole subtree into the client
// bundle for nothing.
