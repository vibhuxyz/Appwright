import {
  breakpoints,
  colors,
  fontFamily,
  fontSize,
  fontWeight,
  letterSpacing,
  radius,
  radiusBase,
  shadows,
  spacing,
} from "../tokens";

// Tailwind v4 is CSS-first: the theme IS a `@theme` block of custom
// properties, and every `--color-x` in it becomes `bg-x`, `text-x`,
// `border-x` for free. So emitting CSS is not a second representation of
// the tokens — it is the only representation Tailwind reads.
//
// The dark values go in a plain `.dark` selector rather than a second
// `@theme`, because `@theme` is resolved once at build time and cannot be
// re-scoped. Redefining the same custom properties under `.dark` is what
// makes a class-based theme toggle work at runtime.

const HEADER = `/* GENERATED by @repo/ui-system — do not edit.
 * Source: libs/ts/ui-system/src/tokens/*.ts
 * Regenerate: bun --filter @repo/ui-system emit
 *
 * Every value an app is allowed to reach for lives here. If a design needs
 * a number that is not in this file, the answer is to add it here once, not
 * to write a bracket value in one component. */\n`;

export function emitTokensCss(): string {
  const lines: string[] = [HEADER];

  // The raw values live WITHOUT the `--color-` prefix, and `@theme inline`
  // maps them into Tailwind's colour namespace. They cannot share a name:
  // `--color-background: var(--color-background)` is a variable defined as
  // itself, which resolves to nothing and silently renders every surface
  // transparent.
  lines.push(":root {");
  lines.push(`  --radius: ${radiusBase};`);
  for (const [name, scale] of Object.entries(colors)) {
    lines.push(`  --${name}: ${scale.light};`);
  }
  lines.push("}\n");

  lines.push(".dark {");
  for (const [name, scale] of Object.entries(colors)) {
    lines.push(`  --${name}: ${scale.dark};`);
  }
  lines.push("}\n");

  lines.push("@theme inline {");
  for (const name of Object.keys(colors)) {
    lines.push(`  --color-${name}: var(--${name});`);
  }
  lines.push("");
  for (const [name, value] of Object.entries(radius)) {
    lines.push(`  --radius-${name}: ${value};`);
  }
  lines.push("");
  for (const [name, value] of Object.entries(spacing)) {
    lines.push(`  --spacing-${name}: ${value};`);
  }
  lines.push("");
  for (const [name, step] of Object.entries(fontSize)) {
    lines.push(`  --text-${name}: ${step.size};`);
    lines.push(`  --text-${name}--line-height: ${step.lineHeight};`);
  }
  lines.push("");
  for (const [name, value] of Object.entries(fontWeight)) {
    lines.push(`  --font-weight-${name}: ${value};`);
  }
  lines.push("");
  for (const [name, value] of Object.entries(fontFamily)) {
    lines.push(`  --font-${name}: ${value};`);
  }
  lines.push("");
  for (const [name, value] of Object.entries(letterSpacing)) {
    lines.push(`  --tracking-${name}: ${value};`);
  }
  lines.push("");
  for (const [name, value] of Object.entries(shadows)) {
    lines.push(`  --shadow-${name}: ${value};`);
  }
  lines.push("");
  for (const [name, value] of Object.entries(breakpoints)) {
    lines.push(`  --breakpoint-${name}: ${value};`);
  }
  lines.push("}\n");

  return lines.join("\n");
}
